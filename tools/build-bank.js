// Generates data/bank.js: lesson positions per technique + rated puzzles per tier.
// Every logical step is checked against the unique solution, so a wrong deduction fails the build.
import { writeFileSync } from 'node:fs';
import * as E from '../app/js/engine.js';

const LESSON_WANT = 30, TIER_WANT = 40, TIME_LIMIT = +(process.env.LIMIT || 420) * 1000;
const rng = E.mulberry32(20261104);
const lessons = Object.fromEntries(E.TECH_ORDER.map(t => [t, []]));
const tiers = { gentle: [], easy: [], medium: [], hard: [], expert: [] };
const LV = Object.fromEntries(E.TECH_ORDER.map((t, i) => [t, i]));
const start = Date.now();
let made = 0;

const full = () => Object.values(lessons).every(a => a.length >= LESSON_WANT) && Object.values(tiers).every(a => a.length >= TIER_WANT);

function check(step, sol) {
  for (const p of step.place) if (sol[p.cell] !== p.digit) throw new Error(`bad place ${step.tech}`);
  for (const e of step.elim) if (sol[e.cell] === e.digit) throw new Error(`bad elim ${step.tech}`);
}

function elimsVsBasic(st) {
  const basic = E.basicCandidates(st.grid), x = [];
  for (let i = 0; i < 81; i++) for (const d of E.digitsOf(basic[i] & ~st.cands[i])) x.push(i * 10 + d);
  return x;
}

while (!full() && Date.now() - start < TIME_LIMIT) {
  const { puzzle, solution } = E.generate(rng);
  made++;
  const st = E.newState(puzzle), took = new Set();
  let pristine = true, max = 0, hardSteps = 0, ok = true;
  while (st.grid.includes(0)) {
    const s = E.findStep(st);
    if (!s) { ok = false; break; }
    check(s, solution);
    const t = s.tech;
    const empties = st.grid.filter(v => !v).length;
    const wantSingle = E.PLACING.has(t) ? pristine && (t !== 'fullHouse' || empties >= 12) : true;
    if (!took.has(t) && wantSingle && lessons[t].length < LESSON_WANT * 2) {
      took.add(t);
      lessons[t].push({ g: E.stringify(st.grid), x: elimsVsBasic(st), s: solution.join(''), e: empties });
    }
    max = Math.max(max, LV[t]);
    if (LV[t] >= LV.xWing) hardSteps++;
    E.applyStep(st, s);
    if (s.elim.length) pristine = false;
  }
  if (!ok) continue;
  const p = { p: E.stringify(puzzle), s: solution.join('') };
  let tier = max <= LV.nakedSingle ? 'easy' : max <= LV.hiddenPair ? 'medium' : (max === LV.swordfish || hardSteps >= 3) ? 'expert' : 'hard';
  if (tiers[tier].length < TIER_WANT) tiers[tier].push(p);
  if (tier === 'easy' && tiers.gentle.length < TIER_WANT) {
    // Gentle: same kind of puzzle with extra clues filled back in.
    const g = puzzle.slice();
    const empty = E.shuffle(g.map((v, i) => (v ? -1 : i)).filter(i => i >= 0), rng);
    while (g.filter(Boolean).length < 38) { const i = empty.pop(); g[i] = solution[i]; }
    tiers.gentle.push({ p: E.stringify(g), s: solution.join('') });
  }
  if (made % 200 === 0) console.log(made, Object.entries(lessons).map(([k, v]) => `${k}:${v.length}`).join(' '), Object.entries(tiers).map(([k, v]) => `${k}:${v.length}`).join(' '));
}

// Prefer the richest positions (most empty cells) for lessons; keep LESSON_WANT.
for (const t of E.TECH_ORDER) {
  lessons[t] = lessons[t].sort((a, b) => b.e - a.e).slice(0, LESSON_WANT).map(({ g, x, s }) => ({ g, x, s }));
}
for (const t of Object.keys(tiers)) tiers[t] = tiers[t].map((p, i) => ({ id: `${t}-${i + 1}`, ...p }));

// ---------- verification ----------
let checked = 0;
for (const [tech, list] of Object.entries(lessons)) for (const pos of list) {
  const grid = E.parse(pos.g), sol = E.parse(pos.s), cands = E.basicCandidates(grid);
  for (const k of pos.x) cands[(k / 10) | 0] &= ~E.bit(k % 10);
  const st = E.newState(grid, cands);
  for (const t of E.TECH_ORDER) {
    if (t === tech) break;
    if (E.findAll(st, t).length) throw new Error(`${tech} position also has easier ${t}`);
  }
  const all = E.findAll(st, tech);
  if (!all.length) throw new Error(`${tech} position has no ${tech}`);
  all.forEach(s => check(s, sol));
  checked++;
}
for (const list of Object.values(tiers)) for (const p of list) {
  const g = E.parse(p.p);
  const r = E.solve(g, 2);
  if (r.count !== 1 || r.solution.join('') !== p.s) throw new Error('not unique ' + p.id);
  if (!E.logicSolve(g).solved) throw new Error('not logic-solvable ' + p.id);
  checked++;
}

writeFileSync(new URL('../app/data/bank.js', import.meta.url), `// Generated by tools/build-bank.js — do not edit.\nexport const BANK = ${JSON.stringify({ lessons, tiers })};\n`);
console.log(`\nGenerated ${made} puzzles in ${((Date.now() - start) / 1000).toFixed(0)}s. Verified ${checked} items.`);
console.log('Lessons:', Object.entries(lessons).map(([k, v]) => `${k}=${v.length}`).join(', '));
console.log('Tiers:', Object.entries(tiers).map(([k, v]) => `${k}=${v.length}`).join(', '));
